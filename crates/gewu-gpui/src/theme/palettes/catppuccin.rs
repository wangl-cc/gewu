use gpui_kit::base::ThemeAppearance;

use super::super::{
    ElevatedShadow, GewuPalette, Theme,
    color::{mix_rgb, rgb, rgba},
};

struct Flavor {
    base: u32,
    mantle: u32,
    crust: u32,
    surface0: u32,
    surface1: u32,
    surface2: u32,
    overlay0: u32,
    overlay2: u32,
    subtext0: u32,
    text: u32,
    mauve: u32,
    red: u32,
    sky: u32,
}

const fn light(f: Flavor) -> GewuPalette {
    GewuPalette {
        canvas: rgb(f.base),
        stripe: rgba(f.surface0, 0.25),
        surface: rgb(f.mantle),
        elevated: rgb(f.base),
        backdrop: rgba(f.text, 0.24),
        border: rgb(f.surface0),
        input_hover: rgb(f.surface2),
        grid: rgb(f.crust),
        elevated_border: rgb(f.surface1),
        foreground: rgb(f.text),
        muted_foreground: rgb(f.subtext0),
        segment_track: rgb(f.crust),
        segment_thumb: rgb(f.base),
        switch_track_off: rgb(f.surface1),
        switch_thumb: rgb(f.base),
        button_secondary: rgba(f.overlay0, 0.22),
        button_secondary_hover: rgba(f.overlay0, 0.34),
        accent: rgb(f.mauve),
        accent_foreground: rgb(f.base),
        accent_hover: mix_rgb(f.mauve, f.text, 0.14),
        accent_pressed: mix_rgb(f.mauve, f.text, 0.24),
        selection_active: rgba(f.overlay2, 0.24),
        selection_inactive: rgba(f.overlay2, 0.14),
        focus_ring: rgba(f.mauve, 0.78),
        find_span: rgba(f.sky, 0.22),
        find_span_current: rgba(f.sky, 0.40),
        find_current_border: mix_rgb(f.sky, f.text, 0.20),
        danger_text: rgb(f.red),
        chart_primary: rgba(f.mauve, 0.80),
        chart_primary_hover: rgb(f.mauve),
        chart_muted: rgba(f.overlay2, 0.30),
        brush_fill: rgba(f.mauve, 0.14),
        chart_grid: rgb(f.crust),
        bar_track: rgb(f.crust),
        shadow: rgb(f.text),
        elevated_shadow: ElevatedShadow::Soft,
    }
}

